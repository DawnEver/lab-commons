"""FEMM's version is MEASURED on every OS: Windows' file version, Linux's install version file.

User ruling 2026-11-25: femm_headless on Linux carries no file version, so it read ``unread`` and a declared
requirement read FEMM absent. The install now carries femm-qt's own build stamp beside the binary
(:data:`~lab_commons.compute.toolchecks.FEMM_VERSION_FILE`), and a missing or unreadable one is a refusal
naming the file and its door -- never ``unread`` as a pass.
"""

from __future__ import annotations

import sys
from datetime import UTC, datetime
from pathlib import Path

import pytest

from lab_commons.compute.presence import Requirement, probe
from lab_commons.compute.toolchecks import (
    FEMM_VERSION_FILE,
    Check,
    VersionUnreadable,
    femm_release,
    femm_version,
)

NOW = datetime(2026, 11, 25, 12, tzinfo=UTC)

#: What femm-qt's cmake/BuildInfo.cmake writes to ``<build>/generated/version.env``.
STAMP = '# GENERATED by cmake/BuildInfo.cmake -- do not edit.\nFEMM_VERSION=5.0.20261112\nFEMM_BUILD=412\n'


def _install(tmp_path: Path, stamp: str | None) -> Path:
    """A femm_headless binary, with *stamp* as its version file when one is given."""
    exe = tmp_path / 'bin' / 'femm_headless'
    exe.parent.mkdir(parents=True)
    exe.write_bytes(b'\x7fELF fake')
    exe.chmod(0o755)
    if stamp is not None:
        (exe.parent / FEMM_VERSION_FILE).write_text(stamp, 'utf-8')
    return exe


def test_linux_reads_the_version_off_the_install_version_file(tmp_path: Path) -> None:
    exe = _install(tmp_path, STAMP)
    assert femm_version(exe, platform='linux') == ('version file', '5.0.20261112')


@pytest.mark.parametrize(
    ('stamp', 'says'),
    [
        (None, 'missing'),  # PLANTED: no version file at all
        ('FEMM_BUILD=412\n', 'no FEMM_VERSION'),  # the key is absent
        ('FEMM_VERSION=\n', 'no FEMM_VERSION'),  # the key is empty
        ('FEMM_VERSION=unread\n', 'no FEMM_VERSION'),  # the old non-reading, written down, is still none
    ],
)
def test_a_missing_or_unreadable_version_file_is_refused_naming_the_file_and_the_door(
    tmp_path: Path, stamp: str | None, says: str
) -> None:
    exe = _install(tmp_path, stamp)
    with pytest.raises(VersionUnreadable) as refused:
        femm_version(exe, platform='linux')
    why = str(refused.value)
    assert says in why
    assert str(exe.parent / FEMM_VERSION_FILE) in why, 'the refusal names the file it looked for'
    assert 'reinstall femm_headless' in why, 'and the door'


def test_an_unreadable_version_is_absent_with_its_refusal_as_evidence_never_unread_as_a_pass(tmp_path: Path) -> None:
    exe = _install(tmp_path, None)
    check = Check(
        lambda: ('install dir', exe), lambda p: femm_version(p, platform='linux'), lambda _p: (True, 'ok'), heavy=True
    )
    for declared in (None, Requirement('5.0', 'r')):
        one = probe('femm', check, declared, now=NOW)
        assert not one.present, 'no declaration makes an unread version present'
        assert one.evidence[-1].source == 'version'
        assert 'reinstall femm_headless' in one.evidence[-1].value
    (exe.parent / FEMM_VERSION_FILE).write_text(STAMP, 'utf-8')
    assert probe('femm', check, None, now=NOW).present, 'PLANTED CONTROL: the same install with its file is present'


@pytest.mark.parametrize(
    ('fixed', 'release'),
    [
        ('5.0.2026.1112', '5.0.20261112'),  # femm-qt splits an 8-digit date patch into YYYY.MMDD
        ('5.0.2026.105', '5.0.20260105'),  # MMDD 0105 is the 16-bit number 105
        ('5.0.2026.1021', '5.0.20261021'),  # measured: this workstation's 2026-10-21 build
        ('5.1.3.0', '5.1.3'),  # any other patch sits in field three with field four 0
    ],
)
def test_the_windows_file_version_decodes_to_femm_qts_one_version_number(fixed: str, release: str) -> None:
    assert femm_release(fixed) == release


@pytest.mark.skipif(sys.platform != 'win32', reason='the file-version reader exists only on Windows')
def test_a_windows_binary_without_a_file_version_is_refused_naming_its_door(tmp_path: Path) -> None:
    exe = tmp_path / 'femm_headlessw.exe'
    exe.write_bytes(b'MZ fake')
    with pytest.raises(VersionUnreadable, match='reinstall femm_headless'):
        femm_version(exe, platform='win32')
